--
-- Name: vendas_por_categoria; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.vendas_por_categoria AS
 SELECT c.nome AS categoria,
    count(DISTINCT i.pedido_id) AS pedidos,
    sum(i.quantidade) AS unidades,
    sum(((i.quantidade)::numeric * i.preco_unitario)) AS receita
   FROM (((public.itens_pedido i
     JOIN public.produtos p ON ((p.id = i.produto_id)))
     JOIN public.categorias c ON ((c.id = p.categoria_id)))
     JOIN public.pedidos o ON (((o.id = i.pedido_id) AND (o.status <> 'cancelado'::public.status_pedido))))
  GROUP BY c.nome;


