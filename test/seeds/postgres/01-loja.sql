--
-- Name: resumo_mensal; Type: MATERIALIZED VIEW; Schema: relatorios; Owner: -
--

CREATE MATERIALIZED VIEW relatorios.resumo_mensal AS
 SELECT (date_trunc('month'::text, criado_em))::date AS mes,
    count(*) AS pedidos,
    sum(total) AS receita,
    round(avg(total), 2) AS ticket_medio
   FROM public.pedidos
  WHERE (status <> 'cancelado'::public.status_pedido)
  GROUP BY ((date_trunc('month'::text, criado_em))::date)
  ORDER BY ((date_trunc('month'::text, criado_em))::date)
  WITH NO DATA;


