CREATE VIEW vendas_por_categoria AS
SELECT c.nome AS categoria, count(DISTINCT i.pedido_id) AS pedidos, sum(i.quantidade) AS unidades,
       sum(i.quantidade * i.preco_unitario) AS receita
FROM itens_pedido i
JOIN produtos p ON p.id = i.produto_id
JOIN categorias c ON c.id = p.categoria_id
JOIN pedidos o ON o.id = i.pedido_id AND o.status <> 'cancelado'
GROUP BY c.nome;

