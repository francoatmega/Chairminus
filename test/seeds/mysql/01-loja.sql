SET NAMES utf8mb4;

CREATE TABLE categorias (
  id int NOT NULL AUTO_INCREMENT,
  nome varchar(80) NOT NULL,
  descricao text,
  PRIMARY KEY (id),
  UNIQUE KEY nome (nome)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE clientes (
  id int NOT NULL AUTO_INCREMENT,
  nome varchar(120) NOT NULL,
  email varchar(120) NOT NULL,
  telefone varchar(20) DEFAULT NULL,
  cidade varchar(80) DEFAULT NULL,
  uf char(2) DEFAULT NULL,
  vip tinyint(1) NOT NULL DEFAULT 0,
  saldo decimal(12,2) NOT NULL DEFAULT 0.00,
  observacoes text,
  criado_em datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY email (email),
  KEY clientes_cidade_idx (uf, cidade)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE produtos (
  id int NOT NULL AUTO_INCREMENT,
  sku varchar(20) NOT NULL,
  nome varchar(160) NOT NULL,
  categoria_id int NOT NULL,
  preco decimal(10,2) NOT NULL,
  estoque int NOT NULL DEFAULT 0,
  ativo tinyint(1) NOT NULL DEFAULT 1,
  atributos json DEFAULT NULL COMMENT 'Cor, material, peso e dimensões',
  criado_em datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY sku (sku),
  KEY produtos_categoria_idx (categoria_id),
  CONSTRAINT fk_produtos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
  CONSTRAINT ck_produtos_preco CHECK (preco >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE pedidos (
  id bigint NOT NULL AUTO_INCREMENT,
  cliente_id int NOT NULL,
  status enum('aberto','pago','enviado','entregue','cancelado') NOT NULL DEFAULT 'aberto',
  forma_pagamento varchar(20) DEFAULT NULL,
  total decimal(12,2) NOT NULL DEFAULT 0.00,
  criado_em datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  enviado_em date DEFAULT NULL,
  atualizado_em datetime DEFAULT NULL,
  PRIMARY KEY (id),
  KEY fk_pedidos_cliente (cliente_id),
  KEY pedidos_status_criado_idx (status, criado_em),
  CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE itens_pedido (
  pedido_id bigint NOT NULL,
  produto_id int NOT NULL,
  quantidade int NOT NULL,
  preco_unitario decimal(10,2) NOT NULL,
  PRIMARY KEY (pedido_id, produto_id),
  KEY fk_itens_produto (produto_id),
  CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id) ON DELETE CASCADE,
  CONSTRAINT fk_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
  CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE avaliacoes (
  id int NOT NULL AUTO_INCREMENT,
  produto_id int NOT NULL,
  cliente_id int NOT NULL,
  nota tinyint NOT NULL,
  comentario text,
  criado_em datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY fk_avaliacoes_produto (produto_id),
  KEY fk_avaliacoes_cliente (cliente_id),
  CONSTRAINT fk_avaliacoes_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE CASCADE,
  CONSTRAINT fk_avaliacoes_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
  CONSTRAINT ck_avaliacoes_nota CHECK (nota BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- No primary key, and repeated rows: saving an edit here needs the LIMIT 1 fallback.
CREATE TABLE log_auditoria (
  em datetime DEFAULT NULL,
  ator varchar(40) DEFAULT NULL,
  acao varchar(120) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

